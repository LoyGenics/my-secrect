export type FetchLike = (url: string, init?: RequestInit) => Promise<Response>;

export interface TransferOptions {
  fetchImpl?: FetchLike;
  /** Attempts per part (>=1). Default 3. Each failed attempt is remembered in the final error. */
  attempts?: number;
  /** Base delay (ms) for exponential backoff between attempts. Default 300. */
  backoffMs?: number;
  /** Parallel part transfers. Default 4. */
  concurrency?: number;
  onProgress?: (done: number, total: number) => void;
}

/** Serialise the Vault-Key-encrypted manifest to the opaque base64 string the API stores. */
export function serializeEncryptedManifest(enc: EncryptedManifest): string {
  return toBase64(new TextEncoder().encode(JSON.stringify(enc)));
}
export function parseEncryptedManifest(b64: string): EncryptedManifest {
  let parsed: unknown;
  try {
    parsed = JSON.parse(new TextDecoder().decode(fromBase64(b64)));
  } catch {
    throw new Error('stored manifest is not a valid encrypted manifest envelope');
  }
  if (!isObj(parsed) || typeof parsed.nonce_b64 !== 'string' || typeof parsed.ciphertext_b64 !== 'string' || typeof parsed.encryption_version !== 'number') {
    throw new Error('stored manifest envelope is malformed');
  }
  return parsed as unknown as EncryptedManifest;
}

export class BlobTransferError extends Error {
  constructor(message: string, readonly partNumber?: number) {
    super(message);
    this.name = 'BlobTransferError';
  }
}

/** Thrown when an upload did not finish. `missingParts` are still to send; call runUpload again to resume. */
export class BlobUploadError extends Error {
  constructor(message: string, readonly missingParts: number[], readonly causes: Error[]) {
    super(message);
    this.name = 'BlobUploadError';
  }
}

function fetchOf(o: TransferOptions): FetchLike {
  const f = o.fetchImpl ?? (globalThis.fetch?.bind(globalThis) as FetchLike | undefined);
  if (!f) throw new Error('no fetch implementation available');
  return f;
}
const sleep = (ms: number) => new Promise<void>((r) => setTimeout(r, ms));

/** HTTP statuses that retrying cannot fix (expired/forged signature, missing object). */
function isPermanent(status: number): boolean {
  return status === 400 || status === 401 || status === 403 || status === 404;
}

async function withRetry<T>(partNumber: number, what: string, o: TransferOptions, fn: () => Promise<T>): Promise<T> {
  const attempts = Math.max(1, o.attempts ?? 3);
  const errors: string[] = [];
  for (let i = 1; i <= attempts; i++) {
    try {
      return await fn();
    } catch (e) {
      const msg = e instanceof Error ? e.message : String(e);
      errors.push(`attempt ${i}: ${msg}`);
      if (e instanceof BlobTransferError && e.message.includes('(permanent)')) break;
      if (i < attempts) await sleep((o.backoffMs ?? 300) * 2 ** (i - 1));
    }
  }
  throw new BlobTransferError(`${what} part ${partNumber} failed — ${errors.join('; ')}`, partNumber);
}

async function putPart(url: string, ciphertext: Uint8Array, partNumber: number, o: TransferOptions): Promise<void> {
  await withRetry(partNumber, 'upload', o, async () => {
    const res = await fetchOf(o)(url, { method: 'PUT', body: ciphertext as unknown as BodyInit, headers: { 'Content-Type': 'application/octet-stream' } });
    if (!res.ok) {
      const hint = res.status === 403 ? ' — presigned URL expired or rejected; start a new upload' : '';
      throw new BlobTransferError(`HTTP ${res.status}${isPermanent(res.status) ? ' (permanent)' : ''}${hint}`, partNumber);
    }
  });
}

async function getPart(url: string, partNumber: number, o: TransferOptions): Promise<Uint8Array> {
  return withRetry(partNumber, 'download', o, async () => {
    const res = await fetchOf(o)(url);
    if (!res.ok) throw new BlobTransferError(`HTTP ${res.status}${isPermanent(res.status) ? ' (permanent)' : ''}`, partNumber);
    return new Uint8Array(await res.arrayBuffer());
  });
}

async function pool<T>(items: T[], concurrency: number, fn: (item: T) => Promise<void>): Promise<Error[]> {
  const errors: Error[] = [];
  let next = 0;
  const workers = Array.from({ length: Math.max(1, Math.min(concurrency, items.length)) }, async () => {
    while (next < items.length) {
      const item = items[next++];
      try { await fn(item); } catch (e) { errors.push(e instanceof Error ? e : new Error(String(e))); }
    }
  });
  await Promise.all(workers);
  return errors;
}

export interface PreparedUpload {
  blobId: string;
  vaultId: string;
  manifest: BlobManifest;
  chunks: EncryptedChunk[];
  urls: Map<number, string>;
  tracker: ResumableUpload;
}

export interface PrepareUploadInput {
  api: BlobApi;
  vaultId: string;
  vaultKey: Uint8Array;
  crypto: CryptoAdapter;
  data: Uint8Array;
  fileName: string;
  mimeType: string;
  /** Plaintext thumbnail bytes generated on THIS device; encrypted with the File Key before it leaves. */
  thumbnail?: { mimeType: string; bytes: Uint8Array };
  blobId?: string;
}

/** Encrypt the file + manifest locally, then ask the API for presigned part URLs. Nothing is uploaded yet. */
export async function prepareUpload(input: PrepareUploadInput): Promise<PreparedUpload> {
  const { api, vaultId, vaultKey, crypto, data } = input;
  await sodiumReady;
  const blobId = input.blobId ?? globalThis.crypto.randomUUID();
  const fileKey = crypto.randomBytes(32);
  try {
    const { chunks, manifest } = await encryptChunks(data, fileKey, blobId, input.mimeType, crypto);
    manifest.file_name = input.fileName;
    if (input.thumbnail) {
      const t = await crypto.encrypt(fileKey, input.thumbnail.bytes);
      manifest.thumbnail = { mime_type: input.thumbnail.mimeType, nonce_b64: toBase64(t.nonce), ciphertext_b64: toBase64(t.ciphertext) };
    }
    await attachWrappedFileKey(manifest, fileKey, vaultKey, crypto);
    verifyManifest(manifest);
    const enc = await buildEncryptedManifest(manifest, vaultKey, crypto);
    const total = chunks.reduce((n, c) => n + c.ciphertext.length, 0);
    const session = await api.createBlobUploadSession(vaultId, {
      blob_id: blobId,
      part_count: chunks.length,
      ciphertext_size: total,
      encrypted_manifest: serializeEncryptedManifest(enc),
    });
    if (session.parts.length !== chunks.length) throw new Error(`server returned ${session.parts.length} upload URLs for ${chunks.length} chunks`);
    const urls = new Map<number, string>();
    for (const p of session.parts) urls.set(p.part_number, p.url);
    for (let n = 1; n <= chunks.length; n++) if (!urls.get(n)) throw new Error(`server returned no upload URL for part ${n}`);
    return { blobId, vaultId, manifest, chunks, urls, tracker: new ResumableUpload(blobId, chunks.length) };
  } finally {
    fileKey.fill(0);
  }
}

/**
 * PUT every not-yet-uploaded part, then call complete. Safe to call again
 * after a BlobUploadError: only the missing parts are re-sent.
 */
export async function runUpload(api: BlobApi, prepared: PreparedUpload, o: TransferOptions = {}): Promise<void> {
  const missing = prepared.tracker.missingParts();
  const errors = await pool(missing, o.concurrency ?? 4, async (n) => {
    await putPart(prepared.urls.get(n) as string, prepared.chunks[n - 1].ciphertext, n, o);
    prepared.tracker.markUploaded(n);
    o.onProgress?.(prepared.tracker.toState().uploaded_parts.length, prepared.chunks.length);
  });
  if (!prepared.tracker.isComplete()) {
    throw new BlobUploadError(`upload incomplete: parts ${prepared.tracker.missingParts().join(', ')} not uploaded (${errors.map((e) => e.message).join(' | ')})`, prepared.tracker.missingParts(), errors);
  }
  // The server re-checks sizes against storage; hashes are what the client committed to.
  const report = await Promise.all(prepared.manifest.chunks.map(async (c) => ({
    part_number: c.part_number,
    ciphertext_size: c.ciphertext_size,
    ciphertext_sha256_b64: c.ciphertext_sha256_b64,
  })));
  await api.completeBlobUpload(prepared.blobId, report);
}

export interface UploadFileResult { blobId: string; manifest: BlobManifest }

/** Convenience: prepare + run in one call (no resume handle on failure; use prepareUpload/runUpload to resume). */
export async function uploadFile(input: PrepareUploadInput, o: TransferOptions = {}): Promise<UploadFileResult> {
  const prepared = await prepareUpload(input);
  await runUpload(input.api, prepared, o);
  return { blobId: prepared.blobId, manifest: prepared.manifest };
}

export interface DownloadedFile {
  bytes: Uint8Array;
  manifest: BlobManifest;
  /** Decrypted thumbnail, if the manifest has one. Decryption failure throws (never silently dropped). */
  thumbnail?: { mimeType: string; bytes: Uint8Array };
}

/**
 * download-session -> decrypt + verify manifest -> unwrap File Key ->
 * fetch every part -> verify count/order/length/hash/nonce -> decrypt.
 * Throws on ANY inconsistency; returns plaintext only if everything checked.
 */
export async function downloadFile(
  api: BlobApi,
  blobId: string,
  vaultKey: Uint8Array,
  crypto: CryptoAdapter,
  o: TransferOptions = {},
): Promise<DownloadedFile> {
  const session = await api.createBlobDownloadSession(blobId);
  if (session.blob_id !== blobId) throw new Error('download session is for a different blob than requested');
  const manifest = await decryptManifest(parseEncryptedManifest(session.encrypted_manifest), vaultKey, crypto);
  if (manifest.blob_id !== blobId) throw new Error('manifest belongs to a different blob — server returned a substituted manifest');
  const wrapped = requireWrappedFileKey(manifest);
  if (session.parts.length !== manifest.chunks.length) throw new Error(`server lists ${session.parts.length} parts, manifest has ${manifest.chunks.length} — truncated or padded`);
  const parts = [...session.parts].sort((a, b) => a.part_number - b.part_number);
  for (let i = 0; i < parts.length; i++) {
    if (parts[i].part_number !== i + 1) throw new Error(`server part list is not 1..N (got ${parts[i].part_number} at ${i + 1})`);
    if (parts[i].ciphertext_size !== manifest.chunks[i].ciphertext_size) throw new Error(`server part ${i + 1} size differs from manifest`);
  }
  const fileKey = await unwrapFileKey(wrapped, vaultKey, crypto);
  try {
    const fetched: EncryptedChunk[] = new Array(parts.length);
    let done = 0;
    const errors = await pool(parts, o.concurrency ?? 4, async (p) => {
      const ciphertext = await getPart(p.url, p.part_number, o);
      fetched[p.part_number - 1] = { part_number: p.part_number, nonce: fromBase64(manifest.chunks[p.part_number - 1].nonce_b64), ciphertext };
      o.onProgress?.(++done, parts.length);
    });
    if (errors.length) throw new BlobTransferError(`download failed: ${errors.map((e) => e.message).join(' | ')}`);
    const bytes = await decryptChunks(fetched, manifest, fileKey, crypto);
    let thumbnail: DownloadedFile['thumbnail'];
    if (manifest.thumbnail) {
      const t = manifest.thumbnail;
      thumbnail = { mimeType: t.mime_type, bytes: await crypto.decrypt(fileKey, fromBase64(t.nonce_b64), fromBase64(t.ciphertext_b64)) };
    }
    return { bytes, manifest, thumbnail };
  } finally {
    fileKey.fill(0);
  }
}

