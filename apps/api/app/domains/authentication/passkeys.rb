require 'base64'
require 'webauthn'
require 'securerandom'

module Authentication
  # WebAuthn/passkeys via the `webauthn` gem (~> 3.0). Account auth only:
  # a verified passkey logs into the ACCOUNT and issues a short-lived
  # Bearer session token. It does NOT unlock the vault and never recovers
  # a decryption key (see specs/key-management.md).
  #
  # Verification is REAL and unconditional — there is no non-production
  # bypass anywhere in this file. Every verify() call goes through
  # WebAuthn::Credential.from_create/from_get(...).verify(...), which
  # checks, against the STORED single-use challenge and the relying-party
  # configuration (config/initializers/webauthn.rb):
  #   * challenge — constant-time comparison with the stored challenge
  #     (challenge is consumed BEFORE verification, so it can never be
  #     replayed even if verification fails);
  #   * origin — clientData origin must equal the configured
  #     WEBAUTHN_ORIGIN (default http://localhost:3000);
  #   * RP ID — SHA-256(configured WEBAUTHN_RP_ID) must equal the rpIdHash
  #     in authenticator data;
  #   * type — webauthn.create for registration, webauthn.get for login;
  #   * user presence (UP flag) and user verification (UV flag) — both
  #     required on every ceremony (options request UV 'required' too);
  #   * signature — assertion signature verified against the STORED public
  #     key of the claimed credential (never a client-supplied key);
  #   * sign count — the gem rejects a non-increasing counter (except
  #     0/0 for synced passkeys that report no counter); the stored count
  #     is advanced monotonically, never decreased.
  # Any failure — malformed input, unknown credential, wrong origin/RP,
  # bad signature, replayed counter — raises VerificationError and issues
  # NO token. Dev/test behave identically to production.
  #
  # Challenges: generated by the gem (WebAuthn::Credential.options_for_*
  # — 32 random bytes, base64url-encoded). The stored string is exactly
  # what verify() expects: the gem base64url-decodes it before comparing.
  # Never store or accept a hex-encoded challenge here — the gem would
  # decode it to different bytes and verification would always fail.
  #
  # Storage (Authenticator model + authenticators table already exist):
  #   credential_id — base64url credential id as returned by the browser
  #     (webauthn_credential.id), unique per authenticator;
  #   public_key    — base64url COSE public key as returned by the gem
  #     (webauthn_credential.public_key); the binary column holds the
  #     ASCII bytes. verify() base64url-decodes it before use.
  #   sign_count    — last verified counter value.
  #
  # Account-takeover guard: this endpoint is unauthenticated, so a
  # 'registration' verification is only accepted when the user has NO
  # active authenticator yet (i.e. account creation with its FIRST
  # passkey). Once an account has a passkey, adding another one must go
  # through the authenticated add-passkey flow
  # (add_registration_options / verify_addition, step-up required).
  # Without this guard, anyone who knows an email address could
  # register a passkey for that account and take it over.
  #
  # The user row is still created at options time in the unauthenticated
  # registration flow (registration_options): the row is inert until step
  # 2 verifies a real attestation — no session is issued before then —
  # and changing it would break the existing register/verify contract.
  # The authenticated add flow (add_registration_options) never creates
  # a user row: the user already exists and is taken from the session,
  # never from a client-supplied email.
  #
  # MFA gate: when the user has MFA enabled, verify() with kind
  # 'authentication' does NOT issue a session. It returns
  # { mfa_required: true, mfa_token: } instead; the client completes the
  # login via Authentication::Totp.complete_mfa_login.
  #
  # The WebAuthn user handle is base64url(user.id bytes): stable, opaque,
  # 48 chars, under the 64-byte limit, and needs no extra column. The
  # assertion is bound to the account by looking the claimed credential
  # id up under THAT user (plus the signature check against the stored
  # key); the userHandle returned by the browser is therefore not used
  # as a lookup key and is not trusted.
  module Passkeys
    class VerificationError < StandardError; end

    CHALLENGE_TTL = 5.minutes
    OPTIONS_TIMEOUT_MS = 300_000 # matches CHALLENGE_TTL; the browser must answer in time
    USER_VERIFICATION = 'required'

    module_function

    # Step 1 (registration): creation options + stored challenge.
    # Creates the user row if new — the account is NOT authenticated
    # until step 2 verifies a real attestation and persists an
    # Authenticator (see verify). Returns the gem's standard options
    # JSON (challenge is base64url; the client base64url-decodes it and
    # user.id before calling navigator.credentials.create).
    def registration_options(email:)
      raise VerificationError, 'email required' if email.blank?
      user = User.find_or_create_by!(email: email.strip.downcase)
      options = WebAuthn::Credential.options_for_create(
        user: { id: webauthn_user_id(user), name: user.email, display_name: user.email },
        exclude: user.authenticators.active.pluck(:credential_id),
        authenticator_selection: { user_verification: USER_VERIFICATION },
        timeout: OPTIONS_TIMEOUT_MS
      )
      PasskeyChallenge.create!(email: user.email, challenge: options.challenge, kind: 'registration', expires_at: Time.current + CHALLENGE_TTL)
      {
        user: { id: user.id, email: user.email },
        creation_options: options.as_json
      }
    end

    # Step 1 (authentication): request options + stored challenge.
    # Exposed as POST /v1/auth/passkeys/authenticate, and reused for
    # step-up passkey verification (StepUp.verify_passkey).
    # Unknown emails still get options with an empty allow-list and a
    # stored challenge, so the response does not leak account existence;
    # step 2 will fail for them with a generic error.
    def authentication_options(email:)
      normalized = email.to_s.strip.downcase
      user = User.find_by(email: normalized)
      allow = user ? user.authenticators.active.pluck(:credential_id) : []
      options = WebAuthn::Credential.options_for_get(
        allow: allow,
        user_verification: USER_VERIFICATION,
        timeout: OPTIONS_TIMEOUT_MS
      )
      PasskeyChallenge.create!(email: normalized, challenge: options.challenge, kind: 'authentication', expires_at: Time.current + CHALLENGE_TTL)
      { request_options: options.as_json }
    end

    # Step 1 (authenticated add): creation options for a user that already
    # exists. No user row is created here and no client-supplied email is
    # trusted — the caller passes the session user. The challenge is
    # stored kind 'registration' under the user's own email, excluding
    # the credential ids the user already has.
    def add_registration_options(user:)
      options = WebAuthn::Credential.options_for_create(
        user: { id: webauthn_user_id(user), name: user.email, display_name: user.email },
        exclude: user.authenticators.active.pluck(:credential_id),
        authenticator_selection: { user_verification: USER_VERIFICATION },
        timeout: OPTIONS_TIMEOUT_MS
      )
      PasskeyChallenge.create!(email: user.email, challenge: options.challenge, kind: 'registration', expires_at: Time.current + CHALLENGE_TTL)
      { creation_options: options.as_json }
    end

    # Step 2 (authenticated add): verify an attestation and bind it to the
    # authenticated user. Same gem verification as verify_registration
    # but WITHOUT the first-passkey-only guard (the caller is already
    # authenticated + stepped up, so the takeover guard does not apply).
    # Issues NO session token — the controller rotates the session
    # instead. Returns the persisted Authenticator.
    def verify_addition(user:, credential:)
      raise VerificationError, 'credential required' if credential.blank?
      # Most recent live challenge: the unauthenticated registration flow
      # can also hold a 'registration' challenge for this email.
      challenge_rec = PasskeyChallenge.live.where(email: user.email, kind: 'registration')
                                           .order(created_at: :desc).first
      raise VerificationError, 'challenge expired or already used' unless challenge_rec
      raise VerificationError, 'challenge expired or already used' unless challenge_rec.consume!
      params = normalize_credential_params(credential)
      verify_registration(user: user, params: params, challenge: challenge_rec.challenge, first_only: false)[:authenticator]
    rescue VerificationError
      raise
    rescue WebAuthn::Error, ArgumentError, TypeError, NoMethodError, RuntimeError
      raise VerificationError, 'verification failed'
    end

    # Step 2: verify an attestation (kind 'registration') or an assertion
    # (kind 'authentication') and, on success only, issue a session token.
    # The challenge is consumed first, so every attempt — valid or not —
    # burns it exactly once. When kind is 'authentication' and the user
    # has MFA enabled, no session is issued: the result is
    # { mfa_required: true, mfa_token: } and the login completes via
    # Authentication::Totp.complete_mfa_login.
    def verify(email:, credential:, kind:, user_agent: nil, ip_address: nil)
      raise VerificationError, 'credential required' if credential.blank?
      kind = kind.to_s
      raise VerificationError, 'unknown ceremony' unless %w[registration authentication].include?(kind)

      normalized_email = email.to_s.strip.downcase
      params = normalize_credential_params(credential)
      challenge_rec = PasskeyChallenge.live.find_by(
        email: normalized_email,
        kind: kind,
        challenge: credential_challenge(params)
      )
      raise VerificationError, 'challenge expired or already used' unless challenge_rec
      raise VerificationError, 'challenge expired or already used' unless challenge_rec.consume!

      user = User.find_by(email: normalized_email)
      raise VerificationError, 'verification failed' unless user

      verified = case kind
                 when 'registration' then verify_registration(user: user, params: params, challenge: challenge_rec.challenge)
                 when 'authentication' then verify_authentication(user: user, params: params, challenge: challenge_rec.challenge)
                 end

      device = user.devices.active.first || Devices::Enroll.call(user: user, public_key: decoded_public_key(verified[:public_key]), name_encrypted: nil)
      Audit::Log.call(user: user, device: device, event_type: "passkey_#{kind}_verified")
      if kind == 'authentication' && user.mfa_enabled?
        mfa_token = MfaTokens.issue(user: user, device: device)
        return { mfa_required: true, mfa_token: mfa_token, user_id: user.id }
      end
      token = SessionTokens.issue(user: user, device: device, user_agent: user_agent, ip_address: ip_address)
      { token: token, user_id: user.id, device_id: device.id, expires_in: SessionTokens::TTL_SECONDS }
    rescue VerificationError
      raise
    rescue WebAuthn::Error, ArgumentError, TypeError, NoMethodError, RuntimeError => _e
      # The gem raises plain RuntimeError for 'invalid type' / 'invalid
      # id', ArgumentError for bad base64url, and WebAuthn::VerificationError
      # subclasses for every failed check. All of them mean the same thing
      # here: the credential did not verify. Fail closed, issue nothing,
      # and do not leak which check failed.
      raise VerificationError, 'verification failed'
    end

    # -- internals ---------------------------------------------------------

    # Base64url encoding of the user's UUID bytes. Opaque, stable, and
    # what the browser stores as the userHandle.
    def webauthn_user_id(user)
      Base64.urlsafe_encode64(user.id.to_s, padding: false)
    end

    # from_create/from_get read String keys ("type", "id", "rawId",
    # "response" => {"clientDataJSON", ...}). Accept a Rails params object
    # or a plain Hash with String or Symbol keys; anything else is not a
    # credential.
    def normalize_credential_params(credential)
      hash =
        if credential.respond_to?(:to_unsafe_h)
          credential.to_unsafe_h
        elsif credential.is_a?(Hash)
          credential
        else
          raise VerificationError, 'credential required'
        end
      hash.deep_stringify_keys
    end

    # Select the exact stored challenge named by clientDataJSON. This is
    # only record lookup: WebAuthn::Credential#verify below still validates
    # the challenge, origin, RP ID, flags, signature, and sign count.
    def credential_challenge(params)
      encoded = params.dig('response', 'clientDataJSON')
      raise VerificationError, 'verification failed' unless encoded.is_a?(String)

      client_data = JSON.parse(WebAuthn::Encoder.new.decode(encoded))
      challenge = client_data['challenge']
      raise VerificationError, 'verification failed' unless challenge.is_a?(String) && challenge.present?

      challenge
    rescue JSON::ParserError, ArgumentError
      raise VerificationError, 'verification failed'
    end

    # Verify an attestation and persist the Authenticator. Returns
    # { public_key:, authenticator: } (public_key is base64url, as the
    # gem returns it, for device binding). With first_only: true (the
    # unauthenticated endpoint) a second passkey is refused — see the
    # module comment. verify_addition passes first_only: false.
    def verify_registration(user:, params:, challenge:, first_only: true)
      # See the module comment: no second passkey via this unauthenticated
      # endpoint once the account already has one.
      raise VerificationError, 'verification failed' if first_only && user.authenticators.active.exists?

      webauthn_credential = WebAuthn::Credential.from_create(params)
      webauthn_credential.verify(challenge, user_presence: true, user_verification: true)
      raise VerificationError, 'verification failed' if webauthn_credential.id.blank? || webauthn_credential.public_key.blank?

      begin
        authenticator = user.authenticators.create!(
          credential_id: webauthn_credential.id,
          public_key: webauthn_credential.public_key,
          sign_count: webauthn_credential.sign_count || 0
        )
      rescue ActiveRecord::RecordInvalid, ActiveRecord::RecordNotUnique
        raise VerificationError, 'verification failed'
      end
      { public_key: webauthn_credential.public_key, authenticator: authenticator }
    end

    # Verify an assertion against the STORED public key / sign count of
    # the claimed credential. Returns { public_key: } (the stored
    # base64url key) for device binding.
    def verify_authentication(user:, params:, challenge:)
      # Parsing alone verifies nothing — it only decodes the envelope so
      # the claimed credential id can be looked up.
      provisional = WebAuthn::Credential.from_get(params)
      raise VerificationError, 'verification failed' if provisional.id.blank?

      authenticator = user.authenticators.active.find_by(credential_id: provisional.id)
      raise VerificationError, 'verification failed' unless authenticator

      # Lock the authenticator row so the sign-count check and the
      # advance are one atomic step: two concurrent verifications cannot
      # both accept the same counter. with_lock reloads the row, so the
      # counter checked below is the committed one.
      authenticator.with_lock do
        # The gem verifies the signature against the stored key, the
        # challenge, origin, RP ID, UP/UV flags, and the sign count
        # (rejects a counter that did not increase — replay protection).
        provisional.verify(
          challenge,
          public_key: authenticator.public_key,
          sign_count: authenticator.sign_count,
          user_presence: true,
          user_verification: true
        )
        # Advance the stored counter monotonically. Synced passkeys report
        # 0 forever (stored stays 0); a real counter only ever increases,
        # so never write a smaller value back.
        new_count = provisional.sign_count || 0
        authenticator.update!(sign_count: new_count) if new_count > authenticator.sign_count
      end
      { public_key: authenticator.public_key }
    rescue OpenSSL::PKey::PKeyError
      raise VerificationError, 'verification failed'
    end

    # Decode a base64url public key (as stored) to raw bytes for
    # Device#public_key. The bytes are the verified COSE public key of
    # the passkey, used ONLY to bind the session's device record to that
    # credential — it is NOT a sync signing key (sync signatures are
    # unverified, H7, and need their own device-key ceremony).
    def decoded_public_key(base64url_key)
      WebAuthn::Encoder.new.decode(base64url_key)
    end
  end
end
